"""Whole LTE RRC C PDU build/run; optional live asn1c bidirectional oracle."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import time

p = argparse.ArgumentParser()
for arg in ('compiler', 'cc', 'runtime', 'root', 'work'):
    p.add_argument('--' + arg, required=True)
p.add_argument('--sanitizers', action='store_true')
p.add_argument('--asn1c')
a = p.parse_args()
root = Path(a.root).resolve()
work = Path(a.work).resolve()
work.mkdir(parents=True, exist_ok=True)
schema = root / 'tests/fixtures/telecom/rrc_8_6_0/EUTRA-RRC-Definitions.asn'
san = ['-fsanitize=address,undefined', '-fno-omit-frame-pointer', '-fno-sanitize-recover=undefined'] if a.sanitizers else []

def run(args, cwd=None):
    result = subprocess.run(list(map(str, args)), cwd=cwd, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f'{args}\n{result.stdout}\n{result.stderr}')
    return result.stdout

# Cover the RRC slice separately; the full-module PDU remains the M1 gate.
slice_out = work / 'rrc-slice'
run([a.compiler, '--lang', 'c', '--codec', 'uper,ber', '--emit-split',
     '--split-max-types', '64', '--emit-dir', slice_out,
     root / 'tests/fixtures/telecom/rrc_slice/rrc_slice.asn'])
slice_manifest = json.loads((slice_out / 'generated-sources.json').read_text())
for name in slice_manifest['sources']:
    run([a.cc, '-std=c11', '-pedantic-errors', '-fsyntax-only', '-I', root / 'include',
         '-I', slice_out, slice_out / name])
resolved_modules = {}
for name, fixture in [('lpp', 'lpp_14_3_0/LPP-PDU-Definitions.asn'),
                      ('s1ap', 's1ap_14_4_0/s1ap_14_4_0.asn')]:
    blocked_out = work / (name + '-resolved')
    result = subprocess.run(list(map(str, [a.compiler, '--lang', 'c', '--codec', 'uper,ber',
        '--emit-dir', blocked_out, root / 'tests/fixtures/telecom' / fixture])),
        capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    manifest = json.loads((blocked_out / 'generated-sources.json').read_text())
    for source in manifest['sources']:
        run([a.cc, '-std=c11', '-pedantic-errors', '-fsyntax-only', '-I', root / 'include',
             '-I', blocked_out, blocked_out / source])
    resolved_modules[name] = len(manifest['sources'])

out = work / 'generated'
run([a.compiler, '--lang', 'c', '--codec', 'uper,ber', '--c-prefix', 'rrc5',
     '--emit-split', '--split-max-types', '128', '--emit-dir', out, schema])
manifest = json.loads((out / 'generated-sources.json').read_text())
assert len(manifest['sources']) > 1 and not manifest['types_only']
assert sum(u['types'] for u in manifest['units'] if u['file'] in manifest['sources']) >= 1000
exe = work / 'rrc-run'
start = time.perf_counter()
run([a.cc, '-std=c11', '-pedantic-errors', *san, '-I', root / 'include', '-I', out,
     *[out / name for name in manifest['sources']], root / 'tests/c_lang/cgen_batch5_rrc_test.c',
     a.runtime, '-lm', '-o', exe])
project = run([exe])
vectors = dict(line.split() for line in project.splitlines())
assert vectors == {'uper': '404080c10158', 'ber': '3015a013a011a008810600010203040581010382020700'}, vectors
evidence = {'schema_sha256': hashlib.sha256(schema.read_bytes()).hexdigest(),
            'sources': len(manifest['sources']), 'types': sum(u['types'] for u in manifest['units'] if u['file'] in manifest['sources']),
            'max_source_bytes': max((out / n).stat().st_size for n in manifest['sources']),
            'compile_run_seconds': round(time.perf_counter() - start, 3), 'vectors': vectors,
            'sanitizers': a.sanitizers, 'rrc_slice_sources': len(slice_manifest['sources']),
            'resolved_modules_syntax': resolved_modules, 'oracle': 'not run'}
if a.asn1c:
    oracle = work / 'asn1c'
    oracle.mkdir(exist_ok=True)
    run([a.asn1c, '-gen-PER', '-fcompound-names', schema], cwd=oracle)
    files = list(oracle.glob('*.c'))
    generated = [f for f in files if 'Generated by asn1c' in f.read_text(errors='replace')[:200]]
    by_descriptor = {}
    for f in generated:
        for name in re.findall(r'asn_TYPE_descriptor_t\s+asn_DEF_(\w+)\s*=', f.read_text(errors='replace')):
            by_descriptor[name] = f
    selected = set()
    def visit(name):
        f = by_descriptor.get(name)
        if f is None or f in selected:
            return
        selected.add(f)
        for dep in re.findall(r'asn_DEF_(\w+)', f.read_text(errors='replace')):
            visit(dep)
    visit('RRCConnectionRequest')
    assert selected
    skeleton = [f for f in files if f not in generated and f.name not in ('converter-example.c', 'pdu_collection.c')]
    oracle_exe = work / 'asn1c-run'
    run([a.cc, '-w', '-I', oracle, *sorted(selected), *skeleton,
         root / 'tests/c_lang/cgen_batch5_rrc_oracle.c', '-lm', '-o', oracle_exe])
    for codec, wire in vectors.items():
        (work / (codec + '.bin')).write_bytes(bytes.fromhex(wire))
    independent = run([oracle_exe, work / 'uper.bin', work / 'ber.bin'])
    assert dict(line.split() for line in independent.splitlines()) == vectors, (project, independent)
    version = subprocess.run([a.asn1c, '-version'], capture_output=True, text=True)
    evidence['oracle'] = (version.stdout + version.stderr).strip()
    evidence['oracle_source_sha256'] = hashlib.sha256(b''.join(f.read_bytes() for f in sorted(files))).hexdigest()
(work / 'evidence.json').write_text(json.dumps(evidence, indent=2) + '\n')
print(json.dumps(evidence, indent=2))
