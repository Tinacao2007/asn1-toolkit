"""仅测试：从同一份完整模式重新编译独立 oracle，生成/复核协议向量。"""
import argparse
import contextlib
import hashlib
import importlib.metadata
import importlib.util
import json
from pathlib import Path
import re
import subprocess
import sys


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def compile_oracle(root, work, protocol, schema):
    from pycrate_asn1c.asnproc import compile_text, generate_modules
    from pycrate_asn1c.generator import PycrateGenerator
    from pycrate_asn1c.glob import GLOBAL
    GLOBAL.clear()
    path = root / schema['path']
    if sha(path) != schema['sha256']:
        raise RuntimeError('schema hash changed: ' + str(path))
    generated = work / ('oracle_' + protocol + '.py')
    with (work / (protocol + '-compile.log')).open('w') as log, contextlib.redirect_stdout(log):
        compile_text(path.read_text(encoding='utf-8'))
        generate_modules(PycrateGenerator, str(generated))
    spec = importlib.util.spec_from_file_location('independent_' + protocol, generated)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module, sha(generated)


def object_for(module, protocol, name):
    owner = {'lpp': 'LPP_PDU_Definitions', 'rrc': 'EUTRA_RRC_Definitions'}
    if protocol == 's1ap':
        owner['s1ap'] = ('S1AP_PDU_Descriptions' if name == 'S1AP-PDU' else
                         'S1AP_PDU_Contents' if name in ('ErrorIndication', 'MMEConfigurationUpdateAcknowledge') else 'S1AP_IEs')
    return getattr(getattr(module, owner[protocol]), name.replace('-', '_'))


def resolve(value, wires):
    if isinstance(value, dict):
        if set(value) == {'$wire'}:
            return wires[value['$wire']].upper()
        return {k: resolve(v, wires) for k, v in value.items()}
    if isinstance(value, list):
        return [resolve(v, wires) for v in value]
    return value


def records(cases):
    rows = []
    for case in cases:
        case = dict(case)
        if case['protocol'] != 's1ap':
            rows.append({**case, 'phase': 'pdu', 'input': case['value']})
            continue
        arm, message = next(iter(case['value'].items()))
        body_type = 'ErrorIndication' if arm == 'initiatingMessage' else 'MMEConfigurationUpdateAcknowledge'
        body_input = {'protocolIEs': []}
        for i, field in enumerate(message['value']['protocolIEs']):
            ident = case['id'] + '-ie-' + str(i)
            kind = {0: 'MME-UE-S1AP-ID', 8: 'ENB-UE-S1AP-ID', 2: 'Cause'}[field['id']]
            rows.append({**case, 'id': ident, 'type': kind, 'phase': 'leaf', 'value': field['value'], 'input': field['value']})
            body_input['protocolIEs'].append({**field, 'value': {'$wire': ident}})
        ident = case['id'] + '-body'
        rows.append({**case, 'id': ident, 'type': body_type, 'phase': 'body', 'value': message['value'], 'input': body_input})
        rows.append({**case, 'phase': 'pdu', 'input': {arm: {**message, 'value': {'$wire': ident}}}})
    return rows


def check_asn1c(root, work, program, cc, catalog, rows, project_runs):
    def run(command, cwd=None):
        result = subprocess.run(list(map(str, command)), cwd=cwd, capture_output=True, timeout=300)
        if result.returncode:
            raise RuntimeError(str(command) + '\n' + result.stderr.decode(errors='replace'))
        return result.stdout
    import asn1tools
    count = 0
    hashes = {}
    for protocol in ('lpp', 'rrc'):
        out = work / ('asn1c-' + protocol)
        out.mkdir(exist_ok=True)
        source = root / catalog['schemas'][protocol]['path']
        run([program, '-gen-PER', '-fcompound-names', source], cwd=out)
        files = sorted(out.glob('*.c'))
        generated = [p for p in files if 'Generated by asn1c' in p.read_text(errors='replace')[:200]]
        descriptors = {}
        for path in generated:
            for name in re.findall(r'asn_TYPE_descriptor_t\s+asn_DEF_(\w+)\s*=', path.read_text(errors='replace')):
                descriptors[name] = path
        selected = set()
        def visit(name):
            path = descriptors.get(name)
            if path is None or path in selected:
                return
            selected.add(path)
            for dependency in re.findall(r'asn_(?:DEF|MBR|SPC)_(\w+)', path.read_text(errors='replace')):
                # asn1c aliases may borrow another file's member/specification
                # arrays without an asn_DEF reference (e.g. MasterInformationBlock).
                while dependency not in descriptors and '_' in dependency:
                    dependency = dependency.rsplit('_', 1)[0]
                visit(dependency)
        for row in rows:
            if row['protocol'] == protocol:
                visit(row['type'].replace('-', '_'))
        if not selected:
            raise RuntimeError('asn1c descriptor closure is empty')
        skeleton = [p for p in files if p not in generated and p.name not in ('converter-example.c', 'pdu_collection.c')]
        executable = out / 'oracle'
        run([cc, '-w', '-DORACLE_' + protocol.upper(), '-I', out, *sorted(selected), *skeleton,
             root / 'tests/telecom/asn1c_protocol_driver.c', '-lm', '-o', executable])
        hashes[protocol] = hashlib.sha256(b''.join(p.read_bytes() for p in files)).hexdigest()
        jer = asn1tools.compile_files(str(source), codec='jer')
        xer = asn1tools.compile_files(str(source), codec='xer')
        for row in rows:
            if row['protocol'] != protocol:
                continue
            value = jer.decode(row['type'], json.dumps(row['value']).encode())
            xml = out / 'value.xml'
            xml.write_bytes(xer.encode(row['type'], value))
            for codec in ('uper', 'ber'):
                encoded = run([executable, row['type'], codec, 'encode', xml]).decode().strip()
                if encoded != row['wire'][codec]:
                    raise RuntimeError('asn1c encoder mismatch: ' + row['id'] + '/' + codec + ': ' + encoded)
                count += 1
                for produced in project_runs:
                    if produced['id'] != row['id'] or produced['codec'] != codec:
                        continue
                    wire = out / 'project.bin'
                    wire.write_bytes(bytes.fromhex(produced['wire']))
                    decoded = run([executable, row['type'], codec, 'decode', wire])
                    actual = xer.decode(row['type'], decoded)
                    if actual != value:
                        raise RuntimeError(f"asn1c project decode mismatch {row['id']}/{codec}/{produced['language']}: "
                                           f"{actual!r} != {value!r}")
                    count += 1
    version = subprocess.run([program, '-version'], capture_output=True, text=True, timeout=10)
    return {'version': (version.stdout + version.stderr).strip(), 'binary_sha256': sha(program),
            'generated_source_sha256': hashes, 'comparisons': count,
            'scope': 'LPP/LTE UPER and BER; this asn1c has no APER oracle'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', required=True)
    p.add_argument('--work', required=True)
    p.add_argument('--output', required=True)
    p.add_argument('--check', help='复核冻结文件；不修改期望值')
    p.add_argument('--project-evidence', help='复核六个真实消费者输出的目录')
    p.add_argument('--asn1c', help='可选第三个独立工具，覆盖 LPP/LTE UPER 和 BER')
    p.add_argument('--cc', default='gcc')
    p.add_argument('--driver', action='append', default=[],
                   help='protocol:language:executable；先运行消费者生成新证据，可重复指定')
    a = p.parse_args()
    root, work = Path(a.root).resolve(), Path(a.work).resolve()
    work.mkdir(parents=True, exist_ok=True)
    if a.driver:
        report_dir = work / 'project-evidence'
        expected = {(protocol, language) for protocol in ('lpp', 's1ap', 'rrc') for language in ('c', 'cpp')}
        supplied = set()
        for item in a.driver:
            protocol, language, executable = item.split(':', 2)
            if (protocol, language) not in expected or (protocol, language) in supplied:
                raise RuntimeError('unexpected or duplicate driver')
            supplied.add((protocol, language))
            subprocess.run([sys.executable, str(root / 'tests/telecom/protocol_replay.py'),
                            '--driver', executable, '--protocol', protocol, '--language', language,
                            '--root', str(root), '--evidence', str(report_dir / (protocol + '-' + language + '.json'))],
                           check=True, timeout=300)
        if supplied != expected:
            raise RuntimeError('all six project drivers are required')
        a.project_evidence = str(report_dir)
    catalog = json.loads((root / 'tests/telecom/protocol_cases.json').read_text(encoding='utf-8'))
    modules, generated_hashes = {}, {}
    for protocol, schema in catalog['schemas'].items():
        modules[protocol], generated_hashes[protocol] = compile_oracle(root, work, protocol, schema)
    oracle_rows = records(catalog['cases'])
    for codec in catalog['codecs']:
        wires = {}
        for row in oracle_rows:
            obj = object_for(modules[row['protocol']], row['protocol'], row['type'])
            obj.from_jer(json.dumps(row['value']))
            wire = getattr(obj, 'to_' + codec)()
            expected = json.loads(obj.to_jer())
            obj.reset_val()
            getattr(obj, 'from_' + codec)(wire)
            if json.loads(obj.to_jer()) != expected:
                raise RuntimeError('independent oracle decode mismatch: ' + row['id'])
            wires[row['id']] = wire.hex()
            row.setdefault('wire', {})[codec] = wire.hex()
            row.setdefault('project_input', {})[codec] = resolve(row['input'], wires)
    # A second independent implementation covers the applicable LPP/LTE values.
    import asn1tools
    second_count = 0
    for protocol in ('lpp', 'rrc'):
        jer = asn1tools.compile_files(str(root / catalog['schemas'][protocol]['path']), codec='jer')
        for codec in catalog['codecs']:
            other = asn1tools.compile_files(str(root / catalog['schemas'][protocol]['path']),
                                          codec='per' if codec == 'aper' else codec)
            for row in oracle_rows:
                if row['protocol'] != protocol:
                    continue
                value = jer.decode(row['type'], json.dumps(row['value']).encode())
                wire = other.encode(row['type'], value)
                if wire.hex() != row['wire'][codec]:
                    raise RuntimeError('independent encoders disagree: ' + row['id'] + '/' + codec)
                decoded = other.decode(row['type'], wire)
                if decoded != value:
                    raise RuntimeError('second oracle semantic mismatch')
                second_count += 1
    from pycrate_asn1rt.err import ASN1Err
    for invalid in catalog['invalid_values']:
        obj = object_for(modules[invalid['protocol']], invalid['protocol'], invalid['type'])
        try:
            obj.from_jer(json.dumps(invalid['value']))
            obj.to_uper()
        except ASN1Err:
            pass
        else:
            raise RuntimeError('independent oracle accepted invalid value: ' + str(invalid))
    package = Path(importlib.util.find_spec('pycrate_asn1rt').origin).parent
    package_hash = hashlib.sha256()
    for path in sorted([*package.glob('*.py'), *(package.parent / 'pycrate_asn1c').glob('*.py')]):
        package_hash.update(path.name.encode())
        package_hash.update(path.read_bytes())
    evidence = {'format': 1, 'catalog_sha256': sha(root / 'tests/telecom/protocol_cases.json'),
                'schemas': catalog['schemas'], 'network_rules': catalog['network_rules'],
                'oracle': {'name': 'pycrate', 'version': importlib.metadata.version('pycrate'),
                           'source_url': 'https://github.com/pycrate-org/pycrate',
                           'package_source_sha256': package_hash.hexdigest(), 'generated_sha256': generated_hashes},
                'second_oracle': {'name': 'asn1tools', 'version': importlib.metadata.version('asn1tools'),
                                  'comparisons': second_count, 'scope': 'LPP/LTE RRC; S1AP table constraints use pycrate'},
                'rows': oracle_rows, 'invalid_values': catalog['invalid_values']}
    if a.check:
        frozen = json.loads(Path(a.check).read_text(encoding='utf-8'))
        if frozen != evidence:
            raise RuntimeError('live evidence differs from frozen metadata/values; explicit reviewed refresh required')
    project_runs = []
    if a.project_evidence:
        expected_keys = {(r['id'], c, language) for r in oracle_rows for c in catalog['codecs']
                         for language in ('c', 'cpp')}
        seen = set()
        by_id = {r['id']: r for r in oracle_rows}
        for path in sorted(Path(a.project_evidence).glob('*.json')):
            report = json.loads(path.read_text(encoding='utf-8'))
            if report.get('catalog_sha256') != evidence['catalog_sha256']:
                raise RuntimeError('stale project report: ' + str(path))
            for produced in report['runs']:
                key = produced['id'], produced['codec'], produced['language']
                if key not in expected_keys or key in seen:
                    raise RuntimeError('duplicate or unexpected project result')
                seen.add(key)
                row = by_id[produced['id']]
                obj = object_for(modules[row['protocol']], row['protocol'], row['type'])
                obj.from_jer(json.dumps(row['value']))
                expected = json.loads(obj.to_jer())
                obj.reset_val()
                getattr(obj, 'from_' + produced['codec'])(bytes.fromhex(produced['wire']))
                if json.loads(obj.to_jer()) != expected:
                    raise RuntimeError('independent decode of PROJECT output failed: ' + str(key))
                project_runs.append(produced)
        if seen != expected_keys:
            raise RuntimeError('missing project output for live reverse decode')
        evidence['project_reverse_decodes'] = len(seen)
    if a.asn1c:
        evidence['asn1c'] = check_asn1c(root, work, a.asn1c, a.cc, catalog, oracle_rows, project_runs)
    Path(a.output).write_text(json.dumps(evidence, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('PASS independent protocol encoders:', len(oracle_rows), 'rows x', len(catalog['codecs']),
          '; second oracle:', second_count)


if __name__ == '__main__':
    main()
